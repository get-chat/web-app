#!/usr/bin/env node
/*
 * Generates the icon components in src/components/icons/ from Material Symbols
 * (Rounded, filled, weight 400, 24px optical size; Apache License 2.0, by
 * Google), downloaded from Google's material-design-icons repository at a
 * pinned commit. The 24px optical size matters: icons drawn for 48px (what the
 * npm packages ship) have thin details that look weak at our 24px.
 *
 * To add an icon, add its Material Symbols name (as on
 * https://fonts.google.com/icons, e.g. "more_vert") to
 * src/components/icons/icons.json and run `node scripts/generate-icons.mjs`.
 * Import it as `@src/components/icons/MoreVert`. The icons' Apache 2.0
 * license is kept next to them in src/components/icons/LICENSE.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

// google/material-design-icons, "Update Symbols" of 2026-10-02
const COMMIT = '737e3324305806514d7909874fa1818ae1808232';

const root = path.resolve(
	path.dirname(new URL(import.meta.url).pathname),
	'..'
);
const iconsDir = path.join(root, 'src/components/icons');
const svgUrl = (name) =>
	`https://raw.githubusercontent.com/google/material-design-icons/${COMMIT}` +
	`/symbols/web/${name}/materialsymbolsrounded/${name}_fill1_24px.svg`;

const toPascalCase = (name) =>
	name
		.split('_')
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join('');

const readPaths = async (name) => {
	const url = svgUrl(name);
	const response = await fetch(url);
	if (!response.ok) {
		throw new Error(
			`No filled Material Symbol named "${name}" (${response.status} ${url})`
		);
	}
	const svg = await response.text();
	const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
	const paths = [...inner.matchAll(/<path d="([^"]+)"\s*\/>/g)].map(
		(m) => m[1]
	);
	if (
		paths.length === 0 ||
		inner.replace(/<path d="[^"]+"\s*\/>/g, '').trim()
	) {
		throw new Error(`Unexpected markup in ${url}`);
	}
	return paths;
};

const names = JSON.parse(
	fs.readFileSync(path.join(iconsDir, 'icons.json'), 'utf8')
);
const header =
	'// Generated by scripts/generate-icons.mjs from Material Symbols (Rounded,\n' +
	'// filled). Do not edit; see that script.\n';

const unique = [...new Set(names)].sort();
const allPaths = await Promise.all(unique.map(readPaths));

// All downloads succeeded: remove the previously generated icons, so dropped
// names don't linger
for (const file of fs.readdirSync(iconsDir)) {
	const full = path.join(iconsDir, file);
	if (
		file.endsWith('.tsx') &&
		fs.readFileSync(full, 'utf8').startsWith(header)
	) {
		fs.unlinkSync(full);
	}
}

const exports = [];
for (const [index, name] of unique.entries()) {
	const component = toPascalCase(name);
	const paths = allPaths[index];
	fs.writeFileSync(
		path.join(iconsDir, `${component}.tsx`),
		`${header}import { createIcon } from './createIcon';\n\n` +
			`export default createIcon(${JSON.stringify(paths)}, '${component}');\n`
	);
	exports.push(`export { default as ${component} } from './${component}';`);
}

fs.writeFileSync(
	path.join(iconsDir, 'index.ts'),
	`${header}export { createIcon } from './createIcon';\n` +
		`export type { IconComponent, IconProps } from './createIcon';\n` +
		exports.join('\n') +
		'\n'
);

execFileSync(
	path.join(root, 'node_modules/.bin/prettier'),
	['--write', '--loglevel', 'warn', iconsDir],
	{ stdio: 'inherit' }
);
console.log(
	`Generated ${exports.length} icons in ${path.relative(root, iconsDir)}`
);
